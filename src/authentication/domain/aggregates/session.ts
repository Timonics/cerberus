import { Clock, DomainError } from '../../../shared/domain';
import { DomainEvent } from '../../../shared/domain/events/domain-event';
import { UserId } from '../../../identity/domain/value-objects/user-id';
import { OrgId } from '../../../identity/domain/value-objects/org-id';
import { IpAddress } from '../value-objects/ip-address';
import { RefreshTokenHash } from '../value-objects/refresh-token-hash';
import { SessionId } from '../value-objects/session-id';
import { UserAgent } from '../value-objects/user-agent';

/**
 * Why a session was revoked. Persisted on the row for support / audit.
 */
export type RevokeReason =
  | 'USER_LOGOUT'
  | 'PASSWORD_CHANGED'
  | 'ADMIN_REVOKED'
  | 'FAMILY_COMPROMISED'
  | 'EXPIRED';

const REVOKE_REASONS: ReadonlySet<RevokeReason> = new Set([
  'USER_LOGOUT',
  'PASSWORD_CHANGED',
  'ADMIN_REVOKED',
  'FAMILY_COMPROMISED',
  'EXPIRED',
]);

export function isRevokeReason(value: unknown): value is RevokeReason {
  return typeof value === 'string' && REVOKE_REASONS.has(value as RevokeReason);
}

/**
 * Session aggregate root.
 *
 * Represents one logged-in device. Created on successful login, mutated
 * on refresh (the refresh hash is rotated but the family stays the same),
 * and revoked on logout / password change / admin action.
 *
 * The "family" concept:
 *   Each session has a `familyId`. On every refresh, the SAME familyId is
 *   reused but the refresh-hash changes. If a refresh token from a
 *   family is presented again AFTER the 60-second rotation grace window
 *   (see `lastRotatedAt`), the family is treated as compromised and ALL
 *   sessions in it are revoked. Within the grace window the retry is
 *   idempotent — legitimate clients double-submit (timeout, two tabs).
 *
 * Invariants:
 *   * `refreshHash` is unique across the table (DB UNIQUE).
 *   * Once `revokedAt` is set, the session is dead — no further mutations.
 *   * `expiresAt` MUST be > `issuedAt`.
 */
export class Session {
  private constructor(
    public readonly id: SessionId,
    public readonly userId: UserId,
    public readonly familyId: string,
    public readonly refreshHash: RefreshTokenHash,
    public readonly userAgent: UserAgent | null,
    public readonly ipAddress: IpAddress | null,
    public readonly deviceLabel: string | null,
    public readonly organizationId: OrgId | null,
    public readonly issuedAt: Date,
    public readonly expiresAt: Date,
    public readonly lastUsedAt: Date | null,
    /**
     * 2026-10-19 audit fix H-7: timestamp of the most recent refresh
     * rotation. Powers the 60-second idempotent-retry grace window —
     * a re-presentation of a just-rotated token within the window is a
     * legitimate client retry (timeout, two tabs), not theft. Null
     * until the first rotation.
     */
    public readonly lastRotatedAt: Date | null,
    /**
     * V1.5: chain of recently-rotated refresh-token hashes. Length is
     * bounded to a small window (5 entries by default). When a presented
     * token's hash is in this list, the presentation is either a
     * legitimate retry (within the `lastRotatedAt` grace window) or
     * theft — RefreshSessionUseCase decides between idempotent retry
     * and family revocation.
     */
    public readonly previousRefreshHashes: ReadonlyArray<string>,
    /**
     * V1.5 (audit C-4): tracks whether the user has completed MFA
     * verification for this session. False on creation when the user
     * has MFA enabled; flipped to true by VerifySecondFactorUseCase.
     * The OAuth password/refresh grants refuse to issue an access
     * token until this is true.
     */
    public readonly mfaVerified: boolean,
    public readonly revokedAt: Date | null,
    public readonly revokeReason: RevokeReason | null,
    private readonly pendingEvents: DomainEvent[],
  ) {}

  /**
   * Create a fresh session (the very first login).
   * `familyId` is generated by the caller (typically the session's own ID,
   * but we accept any opaque string).
   *
   * `organizationId` is the org this session is scoped to. When the
   * login carries `X-Cerberus-App-Id` headers, the controller resolves
   * the org from the app's `defaultOrgSlug` + the user's memberships
   * before calling. When there's no app context, the controller falls
   * back to the user's first org. `null` is accepted for backward
   * compat with V1 callers but treated as "scope to user's first org"
   * by the rest of the system.
   */
  public static create(params: {
    id: SessionId;
    userId: UserId;
    familyId: string;
    refreshHash: RefreshTokenHash;
    userAgent: UserAgent | null;
    ipAddress: IpAddress | null;
    deviceLabel: string | null;
    organizationId: OrgId | null;
    clock: Clock;
    ttlSeconds: number;
    /**
     * V1.5 (audit C-4): whether the user has MFA enabled at session
     * creation. When true, mfaVerified is false — the user must call
     * POST /v1/identity/mfa/verify before the OAuth password/refresh
     * grants will mint an access token. When false, mfaVerified is
     * true (no MFA = nothing to verify, session is "verified" by
     * definition).
     */
    requiresMfa: boolean;
  }): Session {
    const now = params.clock.now();
    const expiresAt = new Date(now.getTime() + params.ttlSeconds * 1000);

    if (expiresAt.getTime() <= now.getTime()) {
      throw new DomainError(
        'domain.invariant_violation',
        'Session TTL must be positive',
      );
    }

    return new Session(
      params.id,
      params.userId,
      params.familyId,
      params.refreshHash,
      params.userAgent,
      params.ipAddress,
      params.deviceLabel,
      params.organizationId,
      now,
      expiresAt,
      null, // lastUsedAt — null on first creation
      null, // lastRotatedAt — null on first creation
      [], // previousRefreshHashes — fresh session
      !params.requiresMfa, // mfaVerified: true if no MFA required
      null, // revokedAt — null on first creation
      null, // revokeReason — null on first creation
      [], // pendingEvents — sessions don't emit events on creation
    );
  }

  public static fromPersistence(params: {
    id: SessionId;
    userId: UserId;
    familyId: string;
    refreshHash: RefreshTokenHash;
    userAgent: UserAgent | null;
    ipAddress: IpAddress | null;
    deviceLabel: string | null;
    organizationId: OrgId | null;
    issuedAt: Date;
    expiresAt: Date;
    lastUsedAt: Date | null;
    /**
     * 2026-10-19 audit fix H-7: most recent rotation timestamp.
     * Optional so rows written before the grace-window migration
     * rehydrate as null (no grace — first retry after the deploy
     * falls through to the compromise path only if actually reused).
     */
    lastRotatedAt?: Date | null;
    /** V1.5: chain of rotated-hashes for reuse detection. */
    previousRefreshHashes?: ReadonlyArray<string>;
    /** V1.5 (audit C-4): MFA-verified flag. Defaults to true so legacy
     *  sessions (pre-V1.5 schema) are still treated as verified. */
    mfaVerified?: boolean;
    revokedAt: Date | null;
    revokeReason: RevokeReason | null;
  }): Session {
    return new Session(
      params.id,
      params.userId,
      params.familyId,
      params.refreshHash,
      params.userAgent,
      params.ipAddress,
      params.deviceLabel,
      params.organizationId,
      params.issuedAt,
      params.expiresAt,
      params.lastUsedAt,
      params.lastRotatedAt ?? null,
      params.previousRefreshHashes ?? [],
      params.mfaVerified ?? true, // legacy sessions are pre-verified
      params.revokedAt,
      params.revokeReason,
      [],
    );
  }

  /**
   * Rotate the refresh token. The new refresh token replaces the old one,
   * `lastUsedAt` is bumped, but the familyId stays the same.
   *
   * If the session is already revoked, this throws — the caller
   * (RefreshSessionUseCase) should have checked via `isAliveAt()` first.
   */
  public rotateRefreshToken(params: {
    newRefreshHash: RefreshTokenHash;
    clock: Clock;
    newExpiresAt: Date;
  }): Session {
    if (this.revokedAt !== null) {
      throw new DomainError(
        'authentication.session.revoked',
        'Cannot rotate a revoked session',
        { sessionId: this.id.value },
      );
    }
    if (params.newExpiresAt.getTime() <= this.issuedAt.getTime()) {
      throw new DomainError(
        'domain.invariant_violation',
        'New expiry must be after the original issue time',
      );
    }
    const now = params.clock.now();
    // V1.5: shift the current refreshHash into previousRefreshHashes
    // (bounded to a small window) so reuse-detection can identify a
    // re-presentation of an old hash. Truncate from the front to
    // keep the array small.
    const PREVIOUS_HASH_WINDOW = 5;
    const newPrevious = [
      this.refreshHash.value,
      ...this.previousRefreshHashes,
    ].slice(0, PREVIOUS_HASH_WINDOW);
    return new Session(
      this.id,
      this.userId,
      this.familyId,
      params.newRefreshHash,
      this.userAgent,
      this.ipAddress,
      this.deviceLabel,
      this.organizationId,
      this.issuedAt,
      params.newExpiresAt,
      now,
      now, // lastRotatedAt — bumped on every rotation
      newPrevious,
      this.mfaVerified, // V1.5 (audit C-4): preserves across rotation
      null, // revokedAt — rotation only happens on live sessions
      null, // revokeReason — null while alive
      this.pendingEvents,
    );
  }

  /**
   * Mark this session revoked. Idempotent — re-revoking with the same
   * reason is a no-op; re-revoking with a different reason throws
   * (defensive: the caller has a stale view of state).
   */
  public revoke(clock: Clock, reason: RevokeReason): Session {
    if (this.revokedAt !== null) {
      if (this.revokeReason === reason) {
        return this;
      }
      throw new DomainError(
        'authentication.session.revoked',
        'Session is already revoked with a different reason',
        {
          sessionId: this.id.value,
          previousReason: this.revokeReason,
          newReason: reason,
        },
      );
    }
    const now = clock.now();
    return new Session(
      this.id,
      this.userId,
      this.familyId,
      this.refreshHash,
      this.userAgent,
      this.ipAddress,
      this.deviceLabel,
      this.organizationId,
      this.issuedAt,
      this.expiresAt,
      this.lastUsedAt,
      this.lastRotatedAt,
      this.previousRefreshHashes,
      this.mfaVerified, // V1.5: revoked sessions preserve the flag for audit
      now,
      reason,
      this.pendingEvents,
    );
  }

  /** True if the session is alive at the given wall-clock time. */
  public isAliveAt(when: Date): boolean {
    if (this.revokedAt !== null) return false;
    return this.expiresAt.getTime() > when.getTime();
  }

  /**
   * V1.5 (audit C-4): mark this session as MFA-verified. Called by
   * VerifySecondFactorUseCase after a successful TOTP / recovery-code
   * match. Idempotent — calling twice is a no-op. Throws if the
   * session is revoked (you can't un-revoke by verifying).
   */
  public markMfaVerified(): Session {
    if (this.revokedAt !== null) {
      throw new DomainError(
        'authentication.session.revoked',
        'Cannot mark MFA-verified on a revoked session',
        { sessionId: this.id.value },
      );
    }
    if (this.mfaVerified) return this; // idempotent
    return new Session(
      this.id,
      this.userId,
      this.familyId,
      this.refreshHash,
      this.userAgent,
      this.ipAddress,
      this.deviceLabel,
      this.organizationId,
      this.issuedAt,
      this.expiresAt,
      this.lastUsedAt,
      this.lastRotatedAt,
      this.previousRefreshHashes,
      true, // mfaVerified
      this.revokedAt,
      this.revokeReason,
      this.pendingEvents,
    );
  }

  public pullDomainEvents(): DomainEvent[] {
    return [...this.pendingEvents];
  }
}
